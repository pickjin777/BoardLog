import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import {
  manifestNodeRemoves,
  nativePackageEnabled,
  stripCapacitorBuildGradle,
  stripCapacitorSettingsGradle,
  withoutMonetizationPlugins
} from './omitNativeMonetization';

const SETTINGS = `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
include ':capacitor-android'
project(':capacitor-android').projectDir = new File('../node_modules/@capacitor/android/capacitor')

include ':capacitor-community-admob'
project(':capacitor-community-admob').projectDir = new File('../node_modules/@capacitor-community/admob/android')

include ':capacitor-splash-screen'
project(':capacitor-splash-screen').projectDir = new File('../node_modules/@capacitor/splash-screen/android')

include ':capgo-native-purchases'
project(':capgo-native-purchases').projectDir = new File('../node_modules/@capgo/native-purchases/android')
`;

const BUILD = `dependencies {
    implementation project(':capacitor-community-admob')
    implementation project(':capacitor-splash-screen')
    implementation project(':capgo-native-purchases')
}
`;

describe('native package flag', () => {
  it('stays off unless the last assignment is the string true', () => {
    expect(nativePackageEnabled('')).toBe(false);
    expect(nativePackageEnabled('# boardlog.monetization=true\n')).toBe(false);
    expect(nativePackageEnabled('boardlog.monetization=false\n')).toBe(false);
    expect(nativePackageEnabled('boardlog.monetization=TRUE\n')).toBe(false);
    expect(nativePackageEnabled('boardlog.monetization=true\n')).toBe(true);
    expect(nativePackageEnabled('  boardlog.monetization = true  \n')).toBe(true);
    expect(nativePackageEnabled('boardlog.monetization=true\nboardlog.monetization=false\n')).toBe(false);
  });
});

describe('strip generated Capacitor files', () => {
  it('drops AdMob and Play Billing and keeps splash', () => {
    const settings = stripCapacitorSettingsGradle(SETTINGS);
    expect(settings).not.toContain('capacitor-community-admob');
    expect(settings).not.toContain('capgo-native-purchases');
    expect(settings).toContain('capacitor-android');
    expect(settings).toContain('capacitor-splash-screen');
    expect(stripCapacitorSettingsGradle(settings)).toBe(settings);

    const build = stripCapacitorBuildGradle(BUILD);
    expect(build).not.toContain('capacitor-community-admob');
    expect(build).not.toContain('capgo-native-purchases');
    expect(build).toContain("implementation project(':capacitor-splash-screen')");
    expect(stripCapacitorBuildGradle(build)).toBe(build);
  });

  it('drops monetization plugins from the runtime list', () => {
    const kept = withoutMonetizationPlugins([
      { pkg: '@capacitor-community/admob', classpath: 'admob.AdMob' },
      { pkg: '@capacitor/splash-screen', classpath: 'splash.Splash' },
      { pkg: '@capgo/native-purchases', classpath: 'billing.Purchases' }
    ]);
    expect(kept).toEqual([{ pkg: '@capacitor/splash-screen', classpath: 'splash.Splash' }]);
    expect(withoutMonetizationPlugins([])).toEqual([]);
  });
});

describe('manifest remove nodes', () => {
  it('reads tools:node only on the named element', () => {
    expect(manifestNodeRemoves('<manifest></manifest>', 'com.example.MISSING')).toBe(false);
    expect(manifestNodeRemoves('android:name="com.example.X">', 'com.example.X')).toBe(false);
    expect(manifestNodeRemoves('<uses-permission android:name="com.example.X"', 'com.example.X')).toBe(false);
    expect(
      manifestNodeRemoves('<uses-permission android:name="com.example.X" tools:node="remove" />', 'com.example.X')
    ).toBe(true);
    expect(manifestNodeRemoves('<uses-permission android:name="com.example.X" />', 'com.example.X')).toBe(false);
  });

  it('strips AD_ID, billing, and the AdMob app id from the shipping manifest', () => {
    const manifest = readFileSync('android/app/src/main/AndroidManifest.xml', 'utf8');
    const properties = readFileSync('android/gradle.properties', 'utf8');
    expect(nativePackageEnabled(properties)).toBe(false);
    expect(manifestNodeRemoves(manifest, 'com.google.android.gms.permission.AD_ID')).toBe(true);
    expect(manifestNodeRemoves(manifest, 'com.android.vending.BILLING')).toBe(true);
    expect(manifestNodeRemoves(manifest, 'com.google.android.gms.ads.APPLICATION_ID')).toBe(true);

    const settings = readFileSync('android/capacitor.settings.gradle', 'utf8');
    const capacitorBuild = readFileSync('android/app/capacitor.build.gradle', 'utf8');
    expect(settings).not.toContain('capacitor-community-admob');
    expect(settings).not.toContain('capgo-native-purchases');
    expect(settings).toContain('capacitor-splash-screen');
    expect(capacitorBuild).not.toContain('capacitor-community-admob');
    expect(capacitorBuild).not.toContain('capgo-native-purchases');
    expect(capacitorBuild).toContain('capacitor-splash-screen');
  });
});
